// Composed examples: queries that combine two or more of this worker's table
// functions the way a real user would (one function supplies the patient, the
// other the clinical rows, joined on the FHIR subject reference). Table
// functions here only accept literal arguments (no LATERAL / subquery args), so
// each side is a filtered search pinned to ExamplePatientID and the two are
// joined on `subject = 'Patient/' || id`.
//
// Each SQL is defined ONCE here and referenced from the driving function's
// Examples (and its vgi.example_queries tag, generated by ExampleQueriesJSON)
// and from the schema-level list in cmd/vgi-fhir-worker/main.go. Every example
// targets the frozen SMART Health IT sandbox (see ExampleBaseURL), so the rows
// quoted in the descriptions stay true.

// ExampleWeightTrend joins fhir_observations to fhir_patients: one patient's
// Body Weight history with the change since the previous measurement.
var ExampleWeightTrend = vgi.CatalogExample{
	Description: "Track one patient's body-weight trend: join their Body Weight Observations (LOINC 29463-7) " +
		"to fhir_patients on the subject reference to label each row with the patient's name, " +
		"and compute the change in kg since the previous measurement.",
	SQL: "SELECT p.given, p.family, o.effective[:10] AS measured_on, round(o.value, 1) AS weight_kg, " +
		"round(o.value - lag(o.value) OVER (ORDER BY o.effective), 1) AS change_kg " +
		"FROM fhir.main.fhir_observations('" + ExampleBaseURL + "', query := 'patient=" + ExamplePatientID + "&code=29463-7') AS o " +
		"JOIN fhir.main.fhir_patients('" + ExampleBaseURL + "', query := '_id=" + ExamplePatientID + "') AS p " +
		"ON o.subject = 'Patient/' || p.id " +
		"ORDER BY o.effective;",
}

// ExampleProblemList joins fhir_search('Condition') to fhir_patients: one
// patient's problem list with clinical status and age at onset.
var ExampleProblemList = vgi.CatalogExample{
	Description: "Build one patient's problem list: search their Condition resources with fhir_search, " +
		"join to fhir_patients on the subject reference, and report each condition's clinical status, " +
		"onset date, and the patient's age in whole years at onset.",
	SQL: "SELECT p.given, p.family, " +
		"json_extract_string(c.resource, '$.code.text') AS condition_name, " +
		"json_extract_string(c.resource, '$.clinicalStatus.coding[0].code') AS clinical_status, " +
		"CAST(json_extract_string(c.resource, '$.onsetDateTime')[:10] AS DATE) AS onset_date, " +
		"date_sub('year', CAST(p.birth_date AS DATE), onset_date) AS age_at_onset " +
		"FROM fhir.main.fhir_search('" + ExampleBaseURL + "', 'Condition', query := 'patient=" + ExamplePatientID + "') AS c " +
		"JOIN fhir.main.fhir_patients('" + ExampleBaseURL + "', query := '_id=" + ExamplePatientID + "') AS p " +
		"ON json_extract_string(c.resource, '$.subject.reference') = 'Patient/' || p.id " +
		"ORDER BY onset_date, condition_name;",
}

// ExampleLatestVitals joins a fhir_read Patient to its fhir_observations and
// aggregates: the most recent numeric vital-sign value per code.
var ExampleLatestVitals = vgi.CatalogExample{
	Description: "Summarise one patient's latest vital signs: read the Patient by id with fhir_read for a display name, " +
		"join it to their vital-signs Observations, and keep the most recent numeric value and unit per vital sign " +
		"(components-only vitals such as Blood Pressure have a NULL value and drop out).",
	SQL: "WITH pt AS (SELECT json_extract_string(resource, '$.id') AS patient_id, " +
		"json_extract_string(resource, '$.name[0].given[0]') || ' ' || json_extract_string(resource, '$.name[0].family') AS patient_name " +
		"FROM fhir.main.fhir_read('" + ExampleBaseURL + "', 'Patient', '" + ExamplePatientID + "')) " +
		"SELECT pt.patient_name, o.code_display, round(arg_max(o.value, o.effective), 1) AS latest_value, " +
		"arg_max(o.unit, o.effective) AS unit, max(o.effective)[:10] AS latest_on " +
		"FROM fhir.main.fhir_observations('" + ExampleBaseURL + "', query := 'patient=" + ExamplePatientID + "&category=vital-signs') AS o " +
		"JOIN pt ON o.subject = 'Patient/' || pt.patient_id " +
		"WHERE o.value IS NOT NULL " +
		"GROUP BY pt.patient_name, o.code_display " +
		"ORDER BY o.code_display;",
}

