// exampleQuery is the described {description, sql} shape of a
// vgi.example_queries entry (VGI515).
type exampleQuery struct {
	Description string `json:"description"`
	SQL         string `json:"sql"`
}

// ExampleQueriesJSON renders examples as the described [{description,sql}] JSON
// list carried by the vgi.example_queries tag, so a tag is always generated from
// the same Examples slice the function advertises natively. HTML escaping is off
// so query strings like `a=1&b=2` stay readable.
func ExampleQueriesJSON(examples []vgi.CatalogExample) string {
	list := make([]exampleQuery, len(examples))
	for i, e := range examples {
		list[i] = exampleQuery{Description: e.Description, SQL: e.SQL}
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(list); err != nil {
		// Only strings are encoded, so this cannot fail.
		panic(err)
	}
	return string(bytes.TrimRight(buf.Bytes(), "\n"))
}

